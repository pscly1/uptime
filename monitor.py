#!/usr/bin/env python3
"""Check a list of endpoints and record the result as a daily snapshot.

Designed to run from GitHub Actions once a day: it writes status/latest.json,
appends to status/history.jsonl, and rewrites STATUS.md for humans. Only the
standard library is used so the workflow needs no install step.
"""

from __future__ import annotations

import json
import ssl
import sys
import time
import urllib.error
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent
STATUS_DIR = ROOT / "status"
TARGETS_FILE = ROOT / "targets.json"

TIMEOUT = 20
USER_AGENT = "pscly-uptime/1.0 (+https://github.com/pscly1/uptime)"


def load_targets():
    with TARGETS_FILE.open(encoding="utf-8") as fh:
        return json.load(fh)["targets"]


def check(name, url, expect=200, timeout=TIMEOUT):
    """Return a result dict. Never raises: a failure is a result."""
    started = time.time()
    result = {
        "name": name,
        "url": url,
        "checked_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "ok": False,
        "status": None,
        "latency_ms": None,
        "detail": "",
    }
    req = urllib.request.Request(url, method="GET")
    req.add_header("User-Agent", USER_AGENT)
    try:
        ctx = ssl.create_default_context()
        with urllib.request.urlopen(req, timeout=timeout, context=ctx) as resp:
            body = resp.read(2048)
            result["status"] = resp.status
            result["latency_ms"] = int((time.time() - started) * 1000)
            result["ok"] = resp.status == expect
            if result["ok"]:
                result["detail"] = f"HTTP {resp.status}, {len(body)}B"
            else:
                result["detail"] = f"expected {expect}, got {resp.status}"
    except urllib.error.HTTPError as exc:
        result["status"] = exc.code
        result["latency_ms"] = int((time.time() - started) * 1000)
        result["ok"] = exc.code == expect
        result["detail"] = f"HTTP {exc.code}"
    except urllib.error.URLError as exc:
        result["latency_ms"] = int((time.time() - started) * 1000)
        result["detail"] = f"unreachable: {exc.reason}"
    except OSError as exc:
        result["latency_ms"] = int((time.time() - started) * 1000)
        result["detail"] = f"timeout or socket error: {exc}"
    return result


def read_history():
    path = STATUS_DIR / "history.jsonl"
    if not path.exists():
        return []
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            rows.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return rows


def uptime_pct(rows, name):
    samples = [r for run in rows for r in run.get("results", []) if r["name"] == name]
    if not samples:
        return None
    up = sum(1 for s in samples if s["ok"])
    return round(100.0 * up / len(samples), 1)


def write_status_md(run, history):
    lines = ["# Status", ""]
    checked = run["checked_at"].replace("T", " ").replace("+00:00", " UTC")
    lines.append(f"Last check: **{checked}**")
    lines.append("")
    lines.append("| endpoint | now | 30-check uptime | last latency | detail |")
    lines.append("| --- | --- | --- | --- | --- |")
    for r in run["results"]:
        state = "up" if r["ok"] else "down"
        pct = uptime_pct(history, r["name"])
        pct_text = "—" if pct is None else f"{pct}%"
        latency = "—" if r["latency_ms"] is None else f"{r['latency_ms']} ms"
        detail = r["detail"].replace("|", "\\|")
        lines.append(f"| {r['name']} | {state} | {pct_text} | {latency} | {detail} |")
    lines.append("")
    lines.append(f"Checks recorded: {len(history)}")
    lines.append("")
    lines.append("Generated by `monitor.py` — see `.github/workflows/monitor.yml`.")
    (ROOT / "STATUS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    STATUS_DIR.mkdir(exist_ok=True)
    targets = load_targets()
    results = [check(t["name"], t["url"], t.get("expect", 200)) for t in targets]
    run = {
        "checked_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "results": results,
    }

    (STATUS_DIR / "latest.json").write_text(
        json.dumps(run, indent=2) + "\n", encoding="utf-8")

    history = read_history()
    history.append(run)
    history = history[-90:]  # keep the file small
    with (STATUS_DIR / "history.jsonl").open("w", encoding="utf-8") as fh:
        for row in history:
            fh.write(json.dumps(row) + "\n")

    write_status_md(run, history)

    down = [r for r in results if not r["ok"]]
    for r in results:
        mark = "ok  " if r["ok"] else "DOWN"
        print(f"{mark} {r['name']:<24} {r['detail']}")
    return 1 if down else 0


if __name__ == "__main__":
    sys.exit(main())
